"""Isolated browser QA against local Firebase emulators; never uses live accounts."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
import json, os, re, time

OUT = Path(os.environ.get('QA_OUTPUT_DIR', 'firebase-qa-results'))
OUT.mkdir(parents=True, exist_ok=True)
URL = os.environ.get('DEMO_URL', 'http://127.0.0.1:8097')
KEY = 'enactus-senior-demo:v1'
stamp = str(time.time_ns())
email_a = f'qa-a-{stamp}@example.test'
email_b = f'qa-b-{stamp}@example.test'
password = 'Mobi-QA-only-482!'
checks, errors = [], []
legacy = {'schemaVersion': 1, 'locale': 'ru', 'draft': None, 'entries': [{
    'id': 'DEMO-legacy-qa', 'operationId': 'legacy-qa', 'kind': 'help',
    'serviceId': 'groceries', 'districtId': 'demo-center', 'slotId': 'demo-morning',
    'status': 'saved-demo', 'createdAt': '2026-11-09T10:00:00.000Z', 'cancelledAt': None,
}]}

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path=os.environ.get('CHROMIUM_PATH'))
    context = browser.new_context(viewport={'width': 390, 'height': 844})
    context.add_init_script(f"if (!localStorage.getItem({json.dumps(KEY)})) localStorage.setItem({json.dumps(KEY)}, {json.dumps(json.dumps(legacy))});")
    page = context.new_page()
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.set_default_timeout(15000)
    def button(name): return page.get_by_role('button', name=name, exact=True)
    def click(name): button(name).click()
    def tab(name): page.get_by_role('tab', name=name, exact=True).click()
    def record(name, condition=True):
        assert condition, name
        checks.append(name)
    def open_entries(): tab('Мои обращения')
    def entry_buttons(): return page.get_by_role('button', name=re.compile('^Открыть запись'))
    def fill_account(email, register=False):
        if register: click('Нет аккаунта? Создать')
        page.get_by_label('Электронная почта', exact=True).fill(email)
        page.get_by_label('Пароль', exact=True).fill(password)
        if register: page.get_by_label('Повторите пароль', exact=True).fill(password)
        click('Создать аккаунт' if register else 'Войти')
    def logged_in(email):
        tab('Аккаунт')
        expect(page.get_by_text(email, exact=True)).to_be_visible()
        expect(button('Выйти из аккаунта')).to_be_enabled()
    try:
        page.goto(URL)
        expect(page.get_by_role('tab', name='Аккаунт', exact=True)).to_be_visible()
        click('Бытовая помощь')
        page.get_by_role('button', name=re.compile('^Выбрать')).first.click()
        click('Далее')
        expect(button('Войти')).to_be_visible()
        record('signed-out application flow requires sign-in')
        page.screenshot(path=str(OUT / 'account-signin-ru.png'), full_page=True)
        fill_account(email_a, register=True)
        expect(button('Далее')).to_be_visible()
        record('registration returns to terms without auto-submit')
        click('Далее')
        page.get_by_role('radio', name='Демонстрационный центр', exact=True).click()
        page.get_by_role('radio', name='Учебный пример: утром', exact=True).click()
        click('Далее')
        click('Сохранить в демо')
        expect(button('Отменить запись в аккаунте')).to_be_visible()
        record('help application saves through Firebase')
        page.screenshot(path=str(OUT / 'account-help-saved.png'), full_page=True)
        page.reload()
        open_entries()
        expect(entry_buttons()).to_have_count(1)
        record('account application survives reload')
        record('legacy local record is preserved and not migrated', page.evaluate('(k)=>JSON.parse(localStorage.getItem(k)).entries.length', KEY) == 1)
        logged_in(email_a)
        click('Выйти из аккаунта')
        expect(button('Войти')).to_be_visible()
        open_entries()
        expect(entry_buttons()).to_have_count(0)
        record('logout hides account applications')
        tab('Аккаунт')
        fill_account(email_b, register=True)
        logged_in(email_b)
        open_entries()
        expect(entry_buttons()).to_have_count(0)
        record('second account cannot see first account applications')
        logged_in(email_b)
        click('Выйти из аккаунта')
        fill_account(email_a)
        logged_in(email_a)
        open_entries()
        expect(entry_buttons()).to_have_count(1)
        record('signing back in restores the owning account history')
        tab('Главная')
        click('Встречи')
        page.get_by_role('button', name=re.compile('^Выбрать')).first.click()
        click('Далее')
        click('Записаться в демо')
        expect(button('Отменить запись в аккаунте')).to_be_visible()
        record('event application saves through Firebase')
        page.reload()
        open_entries()
        expect(entry_buttons()).to_have_count(2)
        record('both kinds of application survive reload')
        entry_buttons().first.click()
        click('Отменить запись в аккаунте')
        click('Оставить')
        expect(button('Отменить запись в аккаунте')).to_be_visible()
        click('Отменить запись в аккаунте')
        click('Подтвердить отмену записи')
        expect(page.get_by_text('Отменено в демо', exact=True).first).to_be_visible()
        record('explicit cancellation succeeds')
        page.reload()
        open_entries()
        expect(entry_buttons()).to_have_count(2)
        expect(page.get_by_text('Отменено в демо', exact=True).first).to_be_visible()
        record('cancelled application remains in account history')
        logged_in(email_a)
        click('Выйти из аккаунта')
        click('Забыли пароль?')
        page.get_by_label('Электронная почта', exact=True).fill(email_a)
        click('Отправить ссылку для сброса')
        expect(page.get_by_text('Если такой аккаунт существует, письмо для сброса пароля отправлено.', exact=True)).to_be_visible()
        record('password reset uses neutral confirmation')
        click('Уже есть аккаунт? Войти')
        click('Қазақша')
        expect(button('Google арқылы кіру')).to_be_visible()
        page.screenshot(path=str(OUT / 'account-signin-kz.png'), full_page=True)
        record('Kazakh account labels are available')
        record('no browser runtime errors', not errors)
    except Exception as error:
        page.screenshot(path=str(OUT / 'failure.png'), full_page=True)
        (OUT / 'failure.txt').write_text(page.locator('body').inner_text(), encoding='utf-8')
        raise
    finally:
        (OUT / 'firebase-smoke-results.json').write_text(json.dumps({'checks': checks, 'pageErrors': errors}, ensure_ascii=False, indent=2), encoding='utf-8')
        print(json.dumps({'passed': len(checks), 'checks': checks, 'pageErrors': errors}, ensure_ascii=False))
        browser.close()
